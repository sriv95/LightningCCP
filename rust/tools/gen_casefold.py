"""Regenerates rust/src/logic/casefold.rs from Python's str.casefold (run from the repo root).

Usage: .venv/bin/python -I rust/tools/gen_casefold.py > rust/src/logic/casefold.rs
"""
print("//! Generated by rust/tools/gen_casefold.py from Python " + __import__("sys").version.split()[0] + ": do not edit.")
print("//! Every code point whose `str.casefold()` differs from `str.lower()`, with its casefold.")
print("pub(super) const CASEFOLD: &[(char, &str)] = &[")
for c in range(0x110000):
    ch = chr(c)
    if ch.casefold() != ch.lower():
        folded = "".join("\\u{%x}" % ord(x) for x in ch.casefold())
        print(f"    ('\\u{{{c:x}}}', \"{folded}\"),")
print("];")
