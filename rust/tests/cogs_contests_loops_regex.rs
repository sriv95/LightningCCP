/// Python accepts these, fancy-regex does not, and the translation cannot help: `\N{name}` inside a set (needs the
/// Unicode name table), lone surrogates (a Rust `char` cannot be one), and `a{2147483647}` (the engine unrolls the
/// count: 2^31 copies; `(a{1000}){1000}` is over the default size limit, kept low at a trust boundary: memory). Also `\ `: the bot strips the pattern first,
/// which leaves a lone backslash that Python rejects too (`a\ b` is in `PYTHON_MATCHES`). Pinned so a change shows up.
const PYTHON_ONLY_ACCEPTED: &[&str] =
    &[r"\ ", r"[\N{LATIN SMALL LETTER A}]", r"a{2147483647}", r"(a{1000}){1000}", r"\ud800", r"\udfff", r"[\ud800-\udfff]"];

/// Python rejects it, but the check needs the Unicode name table to know (`\N{...}` is not looked up).
const RUST_ONLY_ACCEPTED: &[&str] = &[r"\N{nonexistent name}"];

#[test]
fn every_pattern_python_rejects_is_rejected() {
    let mut bad = vec![];
    for (pattern, python_ok) in PYTHON_VERDICTS {
        let rust_ok = check_regex(pattern).is_ok();
        if !python_ok && rust_ok && !RUST_ONLY_ACCEPTED.contains(pattern) {
            bad.push(*pattern);
        }
        if *python_ok && !rust_ok {
            assert!(PYTHON_ONLY_ACCEPTED.contains(pattern), "new gap: Python accepts {pattern:?}");
        }
        if *python_ok && rust_ok {
            assert!(!PYTHON_ONLY_ACCEPTED.contains(pattern), "gap closed: {pattern:?}");
        }
    }
    assert!(bad.is_empty(), "Python rejects, Rust accepts: {bad:?}");
}

#[test]
fn rejections_keep_the_exact_prefix() {
    // Python: re.error "min repeat greater than max repeat at position 2"
    for p in [r"a{2,1}", r"\q", r"(?<n>a)", r"(?<=a+)b", r"(?P<n>a)(?P<n>b)", r"a{2}{3}", r"^*", r"(?-i)a", r"a(?i)", r"[z-a]", r"\x4"] {
        let e = check_regex(p).unwrap_err();
        let m = e.downcast_ref::<BotError>().unwrap_or_else(|| panic!("{p}: a BotError")).to_string();
        assert!(m.starts_with("Invalid regex: "), "{p}: {m}");
    }
    let e = check_regex(r"a{2,1}").unwrap_err().downcast_ref::<BotError>().unwrap().to_string();
    assert!(e.starts_with("Invalid regex: min repeat greater than max repeat"), "{e}");
}

#[test]
fn python_raises_overflow_error_for_a_huge_repeat_so_the_user_sees_something_went_wrong() {
    // Python: OverflowError("the repetition number is too large") is not an re.error: not a BotError
    for p in ["a{4294967295}", "a{4294967296}", "a{99999999999}", "a{1,99999999999}", "a{0,4294967295}"] {
        let e = check_regex(p).unwrap_err();
        assert!(e.downcast_ref::<BotError>().is_none(), "{p}");
        assert_eq!(lightningccp::errors::error_message(&e), "Something went wrong. Try again later.");
    }
}

#[test]
fn valid_python_patterns_stay_accepted() {
    for p in [
        r"a{1,2}", r"a{,3}", r"a{3,}", r"a{x}", r"a{", r"{", r"a{1,2}+", r"(?<=ab|cd)e", r"(?<=\d{3})x", r"(a)(?<=\1)",
        r"(?P<n>a)(?P=n)", r"(a)(?(1)b|c)", r"(?i)a", r"(?i:a)", r"(?-i:a)", r"(?#note)a", r"[a-z\d_-]", r"[\]x]", r"\x41A",
        r"\N{LATIN SMALL LETTER A}", r"^round|educational$", r"(?>a+)b", r"a*+", r"\bword\b", r"(?<!x)y",
    ] {
        assert_eq!(check_regex(p).unwrap(), p);
    }
}

